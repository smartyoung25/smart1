# 기본 관측소 (매핑 실패 시)
_DEFAULT_STATION = 108   # 서울


def find_station(sido: str, sigungu: str = "") -> int:
    """시도 + 시군구 → 가장 가까운 ASOS 관측소 ID 반환.

    Args:
        sido:    시도명 (예: "전라북도", "전북", "경기도")
        sigungu: 시군구명 (예: "군산시", "군산", "") — 없으면 시도 기본 관측소

    Returns:
        ASOS 관측소 ID (int)
    """
    # 시도 정규화 (약칭 허용)
    sido_norm = _SIDO_ALIASES.get(sido, sido)

    # 시군구 정규화 (뒤 공백 제거)
    sgg = sigungu.strip()

    # 1순위: 시도 + 시군구 정확 매핑
    station = _MAPPING.get((sido_norm, sgg))
    if station:
        return station

    # 시군구 뒤 "시/군/구" 접미어 없이 재시도
    if sgg:
        sgg_bare = sgg.rstrip("시군구읍면동")
        station = _MAPPING.get((sido_norm, sgg_bare))
        if station:
            return station

    # 2순위: 시도 기본 관측소
    station = _MAPPING.get((sido_norm, ""))
    if station:
        return station

    # 3순위: 원본 sido 그대로 기본 조회
    station = _MAPPING.get((sido, ""))
    if station:
        return station

    return _DEFAULT_STATION


def list_sido() -> list[str]:
    """등록된 시도 목록 반환 (중복 제거, 정렬)."""
    sidos = {k[0] for k in _MAPPING if k[1] == ""}
    return sorted(sidos)


def list_sigungu(sido: str) -> list[str]:
    """해당 시도의 등록된 시군구 목록 반환 (빈 문자열 제외)."""
    sido_norm = _SIDO_ALIASES.get(sido, sido)
    sgus = [k[1] for k in _MAPPING if k[0] == sido_norm and k[1] != ""]
    return sorted(set(sgus))
